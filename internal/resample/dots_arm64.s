#include "textflag.h"

// func dotsSIMD(y, coef, x *float32, rows, starts *int32, n, taps int)
// 每组 4 个输出各用低 4 路与高 4 路两个累加器，先 VFMUL 后 VFADD；结束时两半相加，再三次 VFADDP 一次写出 4 个结果
TEXT ·dotsSIMD(SB), NOSPLIT, $0-56
	MOVD y+0(FP), R0
	MOVD coef+8(FP), R1
	MOVD x+16(FP), R2
	MOVD rows+24(FP), R3
	MOVD starts+32(FP), R4
	MOVD n+40(FP), R5
	MOVD taps+48(FP), R6
	LSL  $2, R6, R7

group:
	MOVW 0(R3), R8
	MOVW 4(R3), R9
	MOVW 8(R3), R10
	MOVW 12(R3), R11
	MUL  R7, R8, R8
	MUL  R7, R9, R9
	MUL  R7, R10, R10
	MUL  R7, R11, R11
	ADD  R1, R8, R8
	ADD  R1, R9, R9
	ADD  R1, R10, R10
	ADD  R1, R11, R11
	MOVW 0(R4), R12
	MOVW 4(R4), R13
	MOVW 8(R4), R14
	MOVW 12(R4), R15
	ADD  R12<<2, R2, R12
	ADD  R13<<2, R2, R13
	ADD  R14<<2, R2, R14
	ADD  R15<<2, R2, R15
	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	MOVD R6, R16

taps:
	VLD1.P 32(R8), [V16.S4, V17.S4]
	VLD1.P 32(R12), [V18.S4, V19.S4]
	VLD1.P 32(R9), [V20.S4, V21.S4]
	VLD1.P 32(R13), [V22.S4, V23.S4]
	VLD1.P 32(R10), [V24.S4, V25.S4]
	VLD1.P 32(R14), [V26.S4, V27.S4]
	VLD1.P 32(R11), [V28.S4, V29.S4]
	VLD1.P 32(R15), [V30.S4, V31.S4]
	VFMUL  V18.S4, V16.S4, V16.S4
	VFMUL  V19.S4, V17.S4, V17.S4
	VFMUL  V22.S4, V20.S4, V20.S4
	VFMUL  V23.S4, V21.S4, V21.S4
	VFMUL  V26.S4, V24.S4, V24.S4
	VFMUL  V27.S4, V25.S4, V25.S4
	VFMUL  V30.S4, V28.S4, V28.S4
	VFMUL  V31.S4, V29.S4, V29.S4
	VFADD  V16.S4, V0.S4, V0.S4
	VFADD  V17.S4, V1.S4, V1.S4
	VFADD  V20.S4, V2.S4, V2.S4
	VFADD  V21.S4, V3.S4, V3.S4
	VFADD  V24.S4, V4.S4, V4.S4
	VFADD  V25.S4, V5.S4, V5.S4
	VFADD  V28.S4, V6.S4, V6.S4
	VFADD  V29.S4, V7.S4, V7.S4
	SUBS   $8, R16, R16
	BNE    taps

	VFADD  V1.S4, V0.S4, V0.S4
	VFADD  V3.S4, V2.S4, V2.S4
	VFADD  V5.S4, V4.S4, V4.S4
	VFADD  V7.S4, V6.S4, V6.S4
	VFADDP V2.S4, V0.S4, V0.S4
	VFADDP V6.S4, V4.S4, V4.S4
	VFADDP V4.S4, V0.S4, V0.S4
	VST1.P [V0.S4], 16(R0)

	ADD  $16, R3
	ADD  $16, R4
	SUBS $4, R5, R5
	BNE  group
	RET
