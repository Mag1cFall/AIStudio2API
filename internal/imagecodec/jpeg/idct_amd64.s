	VPXOR Y8, Y8, Y8
	VMOVDQU Y8, 0(SI)
	VMOVDQU Y8, 32(SI)
	VMOVDQU Y8, 64(SI)
	VMOVDQU Y8, 96(SI)
	VMOVDQU Y8, 128(SI)
	VMOVDQU Y8, 160(SI)
	VMOVDQU Y8, 192(SI)
