// assistantKeyProject 是 ListCloudProjects 中的云项目
type assistantKeyProject struct {
	name string
	id   string
	free bool
}

// assistantKey 是 ListCloudApiKeys 中的 API key
type assistantKey struct {
	project string
	value   string
}

// resolveAssistantKey 照官网 Gemini Key Resolve 取得新建应用使用的 API key：优先免费层项目中的 key，免费层项目没有 key 时在第一个免费层项目中生成，仍没有时新建项目并在其中生成，都不成时使用其他项目的第一个 key，仍没有时返回空串
func (c *Client) resolveAssistantKey(ctx context.Context, accountID string, model string) (string, error) {
	raw, err := c.assistantRPC(ctx, accountID, MakerSuiteRPCBase, "ListImportedProjects", []any{})
	if err != nil {
		return "", err
	}
	var imported []any
	if err := json.Unmarshal(raw, &imported); err != nil {
		return "", &ProtocolEvidenceError{Method: "ListImportedProjects", Path: "$", Detail: err.Error(), Raw: cloneRaw(raw)}
	}
	names := []string{}
	entries, _ := valueAt(imported, 4).([]any)
	for _, entry := range entries {
		item, _ := entry.([]any)
		if name, _ := valueAt(item, 0).(string); name != "" {
			names = append(names, name)
		}
	}
	if raw, err = c.assistantRPC(ctx, accountID, MakerSuiteRPCBase, "ListCloudProjects", []any{nil, nil, nil, int64(1), nil, names}); err != nil {
		return "", err
	}
	var projects []assistantKeyProject
	for _, item := range nestedRows(raw) {
		name, _ := valueAt(item, 0).(string)
		id, _ := valueAt(item, 1).(string)
		tier, _ := valueAt(item, 5).(float64)
		projects = append(projects, assistantKeyProject{name: name, id: id, free: tier == assistantFreeProjectTier})
	}
	if raw, err = c.assistantProtectedRPC(ctx, accountID, "ListCloudApiKeys", []any{int64(100), nil, int64(1), names, nil},
		AppletProtectedRequest{Model: model, Binding: strings.Join(slices.Sorted(slices.Values(names)), ","), ProofField: 5}); err != nil {
		return "", err
	}
	var keys []assistantKey
	for _, item := range nestedRows(raw) {
		project, _ := valueAt(item, 5).(string)
		value, _ := valueAt(item, 2).(string)
		if value != "" {
			keys = append(keys, assistantKey{project: project, value: value})
		}
	}
	free := slices.DeleteFunc(slices.Clone(projects), func(project assistantKeyProject) bool { return !project.free })
	for _, key := range keys {
		if slices.ContainsFunc(free, func(project assistantKeyProject) bool { return project.name == key.project }) {
			return key.value, nil
		}
	}
	generate := func(project string) string {
		key, err := c.generateAssistantKey(ctx, accountID, model, project)
		if err != nil {
			slog.Warn("Build 写代码助手生成 API key 失败", "account", accountID, "project", project, "error", err)
		}
		return key
	}
	if len(free) > 0 {
		if key := generate(free[0].id); key != "" {
			return key, nil
		}
	}
	if project, err := c.createAssistantProject(ctx, accountID, model); err != nil {
		slog.Warn("Build 写代码助手新建云项目失败", "account", accountID, "error", err)
	} else if key := generate(project); key != "" {
		return key, nil
	}
	if len(keys) > 0 {
		return keys[0].value, nil
	}
	slog.Warn("Build 写代码助手没有可用的 Gemini API key，新建应用不带 key", "account", accountID)
	return "", nil
}

// nestedRows 返回 [[行...]] 形式响应中的各行
func nestedRows(raw json.RawMessage) [][]any {
	var root []any
	if json.Unmarshal(raw, &root) != nil {
		return nil
	}
	list, _ := valueAt(root, 0).([]any)
	rows := make([][]any, 0, len(list))
	for _, entry := range list {
		if row, ok := entry.([]any); ok {
			rows = append(rows, row)
		}
	}
	return rows
}

// createAssistantProject 新建免费层云项目并返回项目 ID，binding 为空串
func (c *Client) createAssistantProject(ctx context.Context, accountID string, model string) (string, error) {
	raw, err := c.assistantProtectedRPC(ctx, accountID, "CreateCloudProject", []any{nil, assistantProjectName, int64(1)},
		AppletProtectedRequest{Model: model, ProofField: 1})
	if err != nil {
		return "", err
	}
	var project []any
	if err := json.Unmarshal(raw, &project); err != nil {
		return "", &ProtocolEvidenceError{Method: "CreateCloudProject", Path: "$", Detail: err.Error(), Raw: cloneRaw(raw)}
	}
	id, _ := valueAt(project, 1).(string)
	if id == "" {
		return "", &ProtocolEvidenceError{Method: "CreateCloudProject", Path: "$[1]", Detail: "缺少项目 ID", Raw: cloneRaw(raw)}
	}
	return id, nil
}

// generateAssistantKey 在云项目中生成 API key 并返回 key，proof 直接绑定项目 ID
func (c *Client) generateAssistantKey(ctx context.Context, accountID string, model string, project string) (string, error) {
	raw, err := c.assistantProtectedRPC(ctx, accountID, "GenerateCloudApiKey", []any{project, nil, nil, assistantKeyName},
		AppletProtectedRequest{Model: model, Digest: project, ProofField: 2})
	if err != nil {
		return "", err
	}
	var root []any
	if err := json.Unmarshal(raw, &root); err != nil {
		return "", &ProtocolEvidenceError{Method: "GenerateCloudApiKey", Path: "$", Detail: err.Error(), Raw: cloneRaw(raw)}
	}
	key, _ := valueAt(root, 0).([]any)
	value, _ := valueAt(key, 2).(string)
	if value == "" {
		return "", &ProtocolEvidenceError{Method: "GenerateCloudApiKey", Path: "$[0][2]", Detail: "缺少 API key", Raw: cloneRaw(raw)}
	}
	return value, nil
}

// createAssistantApplet 照官网从 Build 首页新建应用：取得账户的 API key 后以首条提示与 key 新建应用，没有 key 时不带 key，记入最近使用并把应用 ID 写入账户运行状态；binding 为默认标题与首条提示以空格连接
func (c *Client) createAssistantApplet(ctx context.Context, lease *AccountLease, model string, prompt string) (string, error) {
	accountID := lease.Account().ID
	clicked := time.Now()
	key, err := c.resolveAssistantKey(ctx, accountID, model)
	if err != nil {
		return "", err
	}
	binding := assistantAppletTitle
	if prompt != "" {
		binding += " " + prompt
	}
	var keyField any
	if key != "" {
		keyField = key
	}
	raw, err := c.assistantProtectedRPC(ctx, accountID, "CreateApplet",
		[]any{nil, []any{assistantAppletTitle, assistantAppletDescription, prompt, nil, "default"}, nil, nil, int64(1), keyField, nil, nil},
		AppletProtectedRequest{Model: model, Binding: binding, ProofField: 8})
	if err != nil {
		return "", err
	}
	opened, err := decodeAssistantApplet(raw, "CreateApplet", 1)
	if err != nil {
		return "", err
	}
	if err := lease.setAssistantApplet(opened.applet); err != nil {
		return "", err
	}
	c.assistants.put(accountID, opened)
	c.assistantCompanion(ctx, accountID, MakerSuiteRPCBase, "StoreRecentApplet",
		[]any{[]any{assistantTimestamp(clicked), nil, appletReference(opened.applet), assistantAppletTitle, assistantAppletDescription}})
	return opened.applet, nil
}

// afterAssistantCreated 发送新应用第一段对话提交后官网同时发出的密钥与 trajectory 列表请求
