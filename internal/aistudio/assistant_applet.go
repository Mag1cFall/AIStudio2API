// errAssistantAppletGone 表示账户保存的 Build 应用已不存在
var errAssistantAppletGone = errors.New("Build 写代码助手应用已不存在")

// AppletProtectedTransport 是能为 Build 应用与云项目 RPC 写入 fresh proof 的受保护传输
type AppletProtectedTransport interface {
	DoProtectedApplet(context.Context, AppletProtectedRequest, RPCRequest) (*RPCResponse, error)
}

// AppletProtectedRequest 是 Build 应用与云项目 RPC 的 proof 参数：proof 绑定 Binding 的 SHA-256，Digest 非空时直接绑定 Digest
type AppletProtectedRequest struct {
	Model      string
	Binding    string
	Digest     string
	ProofField int
}

var _ AppletProtectedTransport = (*WorkerProtectedTransport)(nil)

// DoProtectedApplet 写入 fresh proof 后经账户的 WAA 运行时发送 Build 应用与云项目 RPC，页面输入框为空
func (t *WorkerProtectedTransport) DoProtectedApplet(ctx context.Context, request AppletProtectedRequest, rpc RPCRequest) (*RPCResponse, error) {
	selection := AccountSelection{ModelID: request.Model, Method: "generateContent", AccountID: rpc.AccountID}
	proof := ""
	if request.Digest != "" {
		lease, ok := AccountLeaseFromContext(ctx)
		if !ok {
			return nil, fmt.Errorf("受保护请求缺少账户租约")
		}
		worker, err := t.workers.Worker(ctx, lease.Account().ID, request.Model)
		if err != nil {
			return nil, fmt.Errorf("获取账户 WAA preparer: %w", err)
		}
		prepared, err := worker.Prepare(ctx, ProtectedRequest{
			URL: rpc.URL, Headers: rpc.Header.Clone(), Body: rpc.Body, Digest: request.Digest, ProofField: request.ProofField,
		})
		if err != nil {
			return nil, fmt.Errorf("准备 fresh WAA proof: %w", err)
		}
		proof = prepared.Proof
	}
	return t.doPrepared(ctx, request.Binding, "", request.ProofField, proof, selection, rpc)
}

// assistantOpenedApplet 是本进程打开过的账户 Build 应用
type assistantOpenedApplet struct {
	applet string
	// metadata 是应用元数据数组：标题、简介、首条提示、框架与能力
	metadata []any
	// devURL 是应用开发环境地址
	devURL string
}

// title 返回应用元数据中的标题与简介
func (opened assistantOpenedApplet) title() (string, string) {
	title, _ := opened.metadata[0].(string)
	description, _ := opened.metadata[1].(string)
	return title, description
}

// assistantAppletCache 按账户保存本进程打开过的 Build 应用
type assistantAppletCache struct {
	mu       sync.Mutex
	accounts map[string]assistantOpenedApplet
}

func newAssistantAppletCache() *assistantAppletCache {
	return &assistantAppletCache{accounts: make(map[string]assistantOpenedApplet)}
}

// get 返回账户打开过的应用 applet
func (cache *assistantAppletCache) get(accountID string, applet string) (assistantOpenedApplet, bool) {
	cache.mu.Lock()
	defer cache.mu.Unlock()
	opened, ok := cache.accounts[accountID]
	return opened, ok && opened.applet == applet
}

// put 记录账户打开的应用
func (cache *assistantAppletCache) put(accountID string, opened assistantOpenedApplet) {
	cache.mu.Lock()
	defer cache.mu.Unlock()
	cache.accounts[accountID] = opened
}

// setDevURL 记录账户应用的开发环境地址
func (cache *assistantAppletCache) setDevURL(accountID string, applet string, devURL string) {
	cache.mu.Lock()
	defer cache.mu.Unlock()
	if opened, ok := cache.accounts[accountID]; ok && opened.applet == applet && devURL != "" {
		opened.devURL = devURL
		cache.accounts[accountID] = opened
	}
}

// forget 放弃账户打开过的应用，下一轮重新打开
func (cache *assistantAppletCache) forget(accountID string) {
	cache.mu.Lock()
	defer cache.mu.Unlock()
	delete(cache.accounts, accountID)
}

// appletReference 返回 StoreRecentApplet 中的应用引用
func appletReference(applet string) []any {
	return []any{int64(8), nil, nil, nil, nil, nil, nil, nil, []any{applet}}
}

// assistantTimestamp 返回页面以毫秒精度写出的 [秒, 纳秒] 时间戳
func assistantTimestamp(at time.Time) []any {
	return []any{at.Unix(), int64(at.Nanosecond() / int(time.Millisecond) * int(time.Millisecond))}
}

// assistantRPC 以账户身份发送不需要 proof 的 Build 应用 RPC 并返回响应正文
func (c *Client) assistantRPC(ctx context.Context, accountID string, base string, method string, body any) (json.RawMessage, error) {
	data, err := json.Marshal(body)
	if err != nil {
		return nil, err
	}
	rpc := newRPCRequest(method, accountID, "", data, false)
	rpc.URL = base + method
	response, err := c.send(ctx, rpc)
	if err != nil {
		return nil, err
	}
	defer response.Body.Close()
	raw, err := io.ReadAll(response.Body)
	if err != nil {
		return nil, fmt.Errorf("读取 AI Studio %s: %w", method, err)
	}
	return raw, nil
}

// assistantProtectedRPC 以账户身份写入 fresh proof 后发送 Build 应用与云项目 RPC 并返回响应正文
func (c *Client) assistantProtectedRPC(ctx context.Context, accountID string, method string, body any, request AppletProtectedRequest) (json.RawMessage, error) {
	transport, ok := c.protected.(AppletProtectedTransport)
	if !ok {
		return nil, fmt.Errorf("AI Studio 受保护传输不支持 Build 应用请求")
	}
	data, err := json.Marshal(body)
	if err != nil {
		return nil, err
	}
	response, err := transport.DoProtectedApplet(ctx, request, newRPCRequest(method, accountID, "", data, false))
	if err == nil {
		response, err = validateRPCResponse(method, response)
	}
	if err != nil {
		return nil, fmt.Errorf("发送 AI Studio %s: %w", method, err)
	}
	defer response.Body.Close()
	raw, err := io.ReadAll(response.Body)
	if err != nil {
		return nil, fmt.Errorf("读取 AI Studio %s: %w", method, err)
	}
	return raw, nil
}

// assistantCompanion 发送官网页面在同一时刻发出的伴随请求，失败只记入日志
